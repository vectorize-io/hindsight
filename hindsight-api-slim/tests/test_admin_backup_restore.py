@pytest.mark.asyncio
async def test_sequence_sync_rolls_back_with_restore_transaction(backup_test_schema):
    db_url, schema_name, _fq, _embeddings = backup_test_schema
    table = "sequence_rollback_probe"
    conn = await asyncpg.connect(db_url)
    try:
        await conn.execute(
            f"""CREATE TABLE {_fq(table)} (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
            )"""
        )
        assert await conn.fetchval(f"INSERT INTO {_fq(table)} DEFAULT VALUES RETURNING id") == 1

        with pytest.raises(RuntimeError, match="force restore rollback"):
            async with conn.transaction():
                await conn.execute(f"TRUNCATE TABLE {_fq(table)}")
                await conn.execute(f"INSERT INTO {_fq(table)} (id) VALUES (50)")
                await admin_cli._sync_owned_sequences(conn, schema_name, [table])
                raise RuntimeError("force restore rollback")

        assert await conn.fetch(f"SELECT id FROM {_fq(table)} ORDER BY id") == [(1,)]
        assert await conn.fetchval(f"INSERT INTO {_fq(table)} DEFAULT VALUES RETURNING id") == 2
    finally:
        await conn.execute(f"DROP TABLE IF EXISTS {_fq(table)} CASCADE")
        await conn.close()


